const assert=require('node:assert/strict');
const fs=require('node:fs');
const ts=require('typescript');
require.extensions['.ts']=(mod,file)=>mod._compile(ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,file);
const {ReadAloudPlayback,speechChunks}=require('../src/lib/audio/readAloud.ts');
const chunks=speechChunks('หิมะตกหนักและเด็กทั้งหกเดินทางไปยังปราสาท '.repeat(80));
assert(chunks.length>5);assert(chunks.every(c=>c.length<=220));
assert.equal(speechChunks('[ปราสาท](https://example.com) **ยามค่ำ**').join(' '),'ปราสาท ยามค่ำ');
assert.deepEqual(speechChunks('![ภาพ](https://example.com/a.png)'),[]);
let queued=[],updates=[],cancels=0;
const synth={speak:u=>queued.push(u),cancel:()=>cancels++,resume:()=>{}};
const player=new ReadAloudPlayback(synth,text=>({text}),state=>updates.push(state));
const blocks=[{type:'narration',text:'คืนที่หิมะตก'},{type:'sound',text:'โครม!'},{type:'dialogue',speakerName:'Moss',text:'ไปกันเถอะ'},{type:'narration',text:'ทุกคนออกเดินทาง'}];
player.configure({lang:'th-TH',voiceURI:'test'},1.25);
player.play(blocks);
assert.equal(queued.at(-1).rate,1.25);assert.equal(queued.at(-1).lang,'th-TH');assert.equal(updates.at(-1).index,0);
queued.at(-1).onend();assert.equal(updates.at(-1).index,2);assert.match(queued.at(-1).text,/Moss/);
const beforePause=queued.at(-1);
player.pause();assert.equal(updates.at(-1).status,'paused');
let count=queued.length;beforePause.onend();assert.equal(queued.length,count,'cancelled callbacks must never advance');
player.resume();assert.equal(updates.at(-1).index,2);assert.equal(updates.at(-1).status,'playing');
player.configure(null,1.5);assert.equal(queued.at(-1).rate,1.5);
const previous=queued.at(-1);player.play(blocks,3);assert.equal(updates.at(-1).index,3);count=queued.length;previous.onend();assert.equal(queued.length,count);
queued.at(-1).onend();assert.equal(updates.at(-1).status,'idle');
player.play(blocks);queued.at(-1).onerror({error:'not-allowed'});assert.equal(updates.at(-1).status,'idle');assert(updates.at(-1).error);
player.play(blocks);const stale=queued.at(-1);player.stop();count=queued.length;stale.onend();assert.equal(queued.length,count);assert.equal(updates.at(-1).status,'idle');
player.play(blocks);const disposed=queued.at(-1);player.dispose();count=queued.length;disposed.onend();assert.equal(queued.length,count);
player.play([{type:'sound',text:'boom'}]);assert.equal(updates.at(-1).status,'idle');
assert(cancels>5);
const broken=new ReadAloudPlayback({...synth,speak:()=>{throw new Error('unavailable');}},text=>({text}),state=>updates.push(state));
assert.doesNotThrow(()=>broken.play(blocks));assert.equal(updates.at(-1).status,'idle');assert(updates.at(-1).error);
console.log('PASS: Thai chunking, metadata cleanup, block progression, sound skipping, pause/resume, speed, seek, end, errors, stop/dispose and stale-callback isolation.');
